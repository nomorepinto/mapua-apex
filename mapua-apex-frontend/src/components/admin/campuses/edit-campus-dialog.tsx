import { CircleAlertIcon } from "lucide-react"

import { CampusDepartmentsEditor } from "@/components/admin/campuses/campus-departments-editor"
import { useCampusesPage } from "@/components/admin/campuses/campuses-context"
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import { Checkbox } from "@/components/ui/checkbox"
import {
  Dialog,
  DialogClose,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogPanel,
  DialogPopup,
  DialogTitle,
} from "@/components/ui/dialog"
import {
  Field,
  FieldDescription,
  FieldLabel,
} from "@/components/ui/field"
import { Form } from "@/components/ui/form"
import { Input } from "@/components/ui/input"
import { modal } from "@/config"
import { useGibberishField } from "@/hooks/use-gibberish-check"
import { classroomExampleNames } from "@/lib/campus-classroom-format"

export function EditCampusDialog() {
  const { state, actions } = useCampusesPage()
  const nameGibberish = useGibberishField(state.editName)

  return (
    <Dialog
      onOpenChange={(open) => {
        if (!open) actions.closeEdit()
      }}
      open={state.editing !== null}
    >
      <DialogPopup className={modal.dialogMd}>
        <DialogHeader>
          <DialogTitle>Edit campus</DialogTitle>
          <DialogDescription>The campus ID cannot be changed.</DialogDescription>
        </DialogHeader>
        <Form className="contents" onSubmit={actions.handleEditSave}>
          <DialogPanel className="flex flex-col gap-4">
            <Field>
              <FieldLabel htmlFor="edit-campus-id">Campus ID</FieldLabel>
              <Input
                disabled
                id="edit-campus-id"
                readOnly
                type="text"
                value={state.editing?.campus_id ?? ""}
              />
              <FieldDescription>Generated by the API.</FieldDescription>
            </Field>
            <Field>
              <FieldLabel htmlFor="edit-campus-name">Name</FieldLabel>
              <Input
                autoComplete="off"
                id="edit-campus-name"
                onChange={(event) => {
                  nameGibberish.reset()
                  actions.changeEditName(event.currentTarget.value)
                }}
                onBlur={nameGibberish.onBlur}
                required
                type="text"
                value={state.editName}
              />
              {nameGibberish.indicator}
            </Field>
            <div className="flex flex-col gap-4 rounded-lg border border-dashed p-3">
              <p className="text-sm font-medium">Classroom name format</p>
              <p className="text-xs text-muted-foreground">
                Optional. Leave blank for no classroom naming rule. When set, CDM
                can flag a room as a classroom only if its name matches this
                format.
              </p>
              <Field>
                <FieldLabel htmlFor="edit-campus-prefixes">Allowed prefixes</FieldLabel>
                <Input
                  autoComplete="off"
                  id="edit-campus-prefixes"
                  onChange={(event) =>
                    actions.changeEditPrefixes(event.currentTarget.value)
                  }
                  placeholder="MPO, N, W, S, E, NW, SW, SE, NE"
                  type="text"
                  value={state.editPrefixesText}
                />
                <FieldDescription>
                  Comma-separated letters (1-10 each), up to 30 tokens.
                </FieldDescription>
              </Field>
              <Field>
                <FieldLabel htmlFor="edit-campus-digits">Digit count</FieldLabel>
                <Input
                  className="w-24"
                  id="edit-campus-digits"
                  inputMode="numeric"
                  onChange={(event) =>
                    actions.changeEditDigits(event.currentTarget.value)
                  }
                  placeholder="3"
                  type="text"
                  value={state.editDigitsText}
                />
              </Field>
              {classroomExampleNames(state.editPrefixesText, state.editDigitsText) ? (
                <p className="text-xs text-muted-foreground">
                  Classroom names look like{" "}
                  <span className="font-mono">
                    {classroomExampleNames(state.editPrefixesText, state.editDigitsText)}
                  </span>
                </p>
              ) : null}
            </div>
            <CampusDepartmentsEditor
              idPrefix="edit-campus"
              onChange={actions.changeEditDepartments}
              value={state.editDepartments}
            />
            {state.offerEditMain ? (
              <Field>
                <div className="flex items-start gap-2">
                  <Checkbox
                    checked={state.editMain}
                    id="edit-campus-main"
                    name="main"
                    onCheckedChange={(value) => actions.setEditMain(value === true)}
                  />
                  <div className="flex flex-col gap-1">
                    <FieldLabel htmlFor="edit-campus-main">Main campus</FieldLabel>
                    <FieldDescription>
                      Online events are approved by this campus&apos;s OSAAR
                      accounts. Clear it here before another campus can hold the
                      title.
                    </FieldDescription>
                  </div>
                </div>
              </Field>
            ) : null}
            {state.editError ? (
              <Alert variant="error">
                <CircleAlertIcon />
                <AlertTitle>Could not save</AlertTitle>
                <AlertDescription>{state.editError}</AlertDescription>
              </Alert>
            ) : null}
            {state.deleteError ? (
              <Alert variant="error">
                <CircleAlertIcon />
                <AlertTitle>Could not delete</AlertTitle>
                <AlertDescription>{state.deleteError}</AlertDescription>
              </Alert>
            ) : null}
          </DialogPanel>
          <DialogFooter>
            <Button
              onClick={actions.openDelete}
              type="button"
              variant="destructive-outline"
            >
              Delete
            </Button>
            <DialogClose render={<Button type="button" variant="ghost" />}>
              Cancel
            </DialogClose>
            <Button
              disabled={
                nameGibberish.state === "gibberish" ||
                nameGibberish.state === "checking"
              }
              loading={state.updatePending}
              type="submit"
            >
              Save changes
            </Button>
          </DialogFooter>
        </Form>
      </DialogPopup>
    </Dialog>
  )
}
